"""Regenerate the embedded PTX using NVIDIA CUDA Rust on Linux or rustc NVPTX on Windows."""
import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--platform", choices=("windows", "linux"), default="windows" if sys.platform == "win32" else "linux")
parser.add_argument("--check", action="store_true", help="Check that both embedded artifacts match their current Rust sources")
args = parser.parse_args()


def fingerprint(platform):
    project = root / "tools/cuda" / platform
    sources = [root / "tools/cuda/kernels.rs", project / "Cargo.toml", project / "Cargo.lock", project / "rust-toolchain.toml"]
    sources += sorted((project / "src").glob("*.rs"))
    return hashlib.sha256(b"".join(p.read_bytes().replace(b"\r\n", b"\n") for p in sources)).hexdigest()


if args.check:
    for platform in ("windows", "linux"):
        artifact = root / "fcs-utils/src/cuda" / (platform + ".ptx")
        assert f"// Source SHA256: {fingerprint(platform)}" in artifact.read_text(), f"Regenerate {platform} PTX with tools/cuda/build.py"
    print("Embedded CUDA artifacts match their Rust sources")
    sys.exit(0)

project = root / "tools/cuda" / args.platform
if args.platform == "windows":
    subprocess.run([
        "cargo", "+nightly-2026-08-24", "rustc", "--manifest-path", str(project / "Cargo.toml"),
        "--target-dir", str(root / "target/cuda-kernels"), "--target", "nvptx64-nvidia-cuda",
        "-Z", "build-std=core", "--release", "--", "--emit=asm",
    ], cwd=root, check=True)
    candidates = list((root / "target/cuda-kernels/nvptx64-nvidia-cuda/release").rglob("fcs_cuda_kernels*.s"))
else:
    subprocess.run(["cargo", "oxide", "build", "--arch", "sm_80"], cwd=project, check=True)
    candidates = [project / "fcs_cuda_kernels.ptx"]
assert len(candidates) == 1, candidates
ptx = candidates[0].read_text()
assert ".extern .func" not in ptx, "PTX must be self-contained; found an unresolved device function"
entries = re.findall(r"\.entry\s+(\w+)\s*\(", ptx)
for name in re.findall(r"fn (fcs_\w+)\(", (root / "tools/cuda/kernels.rs").read_text()):
    matches = [entry for entry in entries if entry == name or entry.endswith("_" + name)]
    assert len(matches) == 1, (name, entries)
    ptx = re.sub(r"\b" + re.escape(matches[0]) + r"\b", name, ptx)
output = root / "fcs-utils/src/cuda" / (args.platform + ".ptx")
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text("// Generated by tools/cuda/build.py; edit tools/cuda/kernels.rs.\n" + f"// Source SHA256: {fingerprint(args.platform)}\n" + ptx, newline="\n")
print(output)
